#!/usr/bin/env node
'use strict';
// Writes meta/skill-headings.json: per skill the stack ships, a hash of every SKILL.md heading (frontmatter `name` +
// `description`) it has shipped under that folder name - every state of `stack/skills/<name>/SKILL.md` and the older
// top-level `skills/<name>/SKILL.md` in git history, plus the working tree's. The installer's M3 test reads it to know
// an older stack copy from a project's own skill (scripts/install/skill-headings.js). Only names the stack ships now: a
// renamed or retired name's copy is the rename and prune paths' (the manifest's `renamed` / `retired` rows), and its
// old name stays out of shipped text. Append-only within a name: a hash already in the file stays, so a shallow clone
// never drops history it cannot see.
//
//   node scripts/skill-headings.js [--root <repo>]      (npm run skill-headings)
const fs = require('node:fs');
const path = require('node:path');
const rt = require('./install/runtime.js');   // every external command through the one Windows-safe spawn (M6)
const { FILE, headingOf, headingHash } = require('./install/skill-headings.js');

const SKILL_PATH = /^(?:stack\/)?skills\/([^/]+)\/SKILL\.md$/;
const ZERO = /^0+$/;

function collect(root)
{
    const out = new Map();
    const add = (name, text) =>
    {
        const heading = headingOf(text);
        if (!heading) return;
        if (!out.has(name)) out.set(name, new Set());
        out.get(name).add(headingHash(heading));
    };
    // Every blob either side of each change to a SKILL.md, keyed by its folder name.
    const blobs = new Map();
    let raw = '';
    try
    {
        raw = rt.execCommand('git', ['-C', root, 'log', '--all', '--format=', '--raw', '--no-abbrev', '--no-renames', '--', 'stack/skills/*/SKILL.md', 'skills/*/SKILL.md'],
            { encoding: 'utf8', maxBuffer: 1 << 30, stdio: ['ignore', 'pipe', 'pipe'] });
    }
    catch { raw = ''; }   // not a git checkout: the working tree's headings alone
    for (const line of raw.split('\n'))
    {
        const m = /^:\d+ \d+ ([0-9a-f]+) ([0-9a-f]+) [A-Z]\d*\t(.+)$/.exec(line);
        const p = m && SKILL_PATH.exec(m[3]);
        if (!p) continue;
        for (const blob of [m[1], m[2]]) if (!ZERO.test(blob)) blobs.set(blob, p[1]);
    }
    if (blobs.size)
    {
        // One cat-file process for every blob: `<sha> blob <size>\n<content>\n` per entry.
        const ids = [...blobs.keys()];
        const buf = rt.execCommand('git', ['-C', root, 'cat-file', '--batch'], { input: ids.join('\n') + '\n', maxBuffer: 1 << 30, stdio: ['pipe', 'pipe', 'pipe'] });
        let at = 0;
        for (const id of ids)
        {
            const nl = buf.indexOf(0x0a, at);
            const head = buf.subarray(at, nl).toString('utf8').split(' ');
            const size = Number(head[2]);
            if (head[1] !== 'blob' || !Number.isFinite(size)) { at = nl + 1; continue; }
            add(blobs.get(id), buf.subarray(nl + 1, nl + 1 + size).toString('utf8'));
            at = nl + 1 + size + 1;
        }
    }
    const dir = path.join(root, 'stack', 'skills');
    const shipped = new Set();
    for (const name of fs.existsSync(dir) ? fs.readdirSync(dir) : [])
    {
        const file = path.join(dir, name, 'SKILL.md');
        if (fs.existsSync(file)) { shipped.add(name); add(name, fs.readFileSync(file, 'utf8')); }
    }
    for (const name of [...out.keys()]) if (!shipped.has(name)) out.delete(name);
    return out;
}

function write(root)
{
    const file = path.join(root, FILE);
    let prior = {};
    try { prior = JSON.parse(fs.readFileSync(file, 'utf8')).skills || {}; } catch { prior = {}; }
    const found = collect(root);
    for (const [name, list] of Object.entries(prior))
    {
        if (!found.has(name)) continue;   // no longer shipped
        for (const h of list) found.get(name).add(h);
    }
    const skills = Object.fromEntries([...found.keys()].sort().map((name) => [name, [...found.get(name)].sort()]));
    const data = {
        about: 'GENERATED by scripts/skill-headings.js (npm run skill-headings) - never edit by hand. Per skill the stack ships, the first 16 hex of sha256 over `name\\ndescription` (frontmatter values as written) of every SKILL.md heading the stack has shipped. The installer claims a same-named copy the stamp does not record when its heading hashes to one of these (M3, scripts/install/skill-headings.js); lint check 64 fails when a current heading is missing.',
        skills,
    };
    const text = `${JSON.stringify(data, null, 2)}\n`;
    const changed = !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text;
    if (changed) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); }
    return { file, changed, names: Object.keys(skills).length, hashes: Object.values(skills).reduce((n, l) => n + l.length, 0) };
}

if (require.main === module)
{
    const i = process.argv.indexOf('--root');
    const root = path.resolve(i === -1 ? path.join(__dirname, '..') : process.argv[i + 1]);
    const r = write(root);
    console.log(`${r.changed ? 'wrote' : 'unchanged'} ${path.relative(root, r.file)} - ${r.names} skill names, ${r.hashes} headings`);
}

module.exports = { collect, write };
